// --- Game registration --------------------------------------------------
// recompui's own default launcher menu (ui_launcher.cpp) reads this exact
// global by name -- it must exist with this type for the link to succeed.
std::vector<recomp::GameEntry> supported_games = {
    {
        // XXH3_64 of the normalized big-endian .z64 (tools/normalize_rom.py)
        // of the USA rev 0 ROM (internal name BATTLEZONE, game code NZOE;
        // SHA-1 of the original byteswapped .n64 dump
        // cdd1d1dec9763ce6b7b1a70668effcead0a185a0) -- NOT the N64 header
        // CRC1/CRC2.
        .rom_hash = 0xf5f240b373301b9dULL,
        .internal_name = "BATTLEZONE",
        .display_name = "Battlezone: Rise of the Black Dogs",
        .game_id = u8"bz.n64.us.1.0",
        .mod_game_id = "bz",
        // TODO(bz): confirm the save media. Assumed Controller Pak
        // (src/game/controller_pak_hle.cpp) like most N64 titles of the era;
        // AllowAll keeps the runtime answering any EEPROM/SRAM/Flash probe
        // sensibly until that's checked.
        .save_type = recomp::SaveType::AllowAll,
        .thumbnail_bytes = {},
        .is_enabled = true,
        .decompression_routine = nullptr,
        .has_compressed_code = false,
        // entrypoint_address is a gpr (uint64_t). A plain 0x80028400 literal
        // zero-extends to 0x0000000080028400 -- but the MEM_B/MEM_W/MEM_H
        // macros (N64Recomp/include/recomp.h) subtract the *sign-extended*
        // KSEG0 base (0xFFFFFFFF80000000, matching real MIPS64 register
        // semantics: a 32-bit value in a 64-bit register is always sign-
        // extended), so a zero-extended address computes a ~4GB-off offset
        // into rdram instead of the intended small one, segfaulting on the
        // very first RDRAM write in do_rom_read(). Cast through int32_t
        // first to sign-extend, matching what N64Recomp's own generated
        // get_entrypoint_address() (RecompiledFuncs/lookup.cpp) does for
        // exactly this reason.
        .entrypoint_address = (gpr)(int32_t)0x80028400u,
        .entrypoint = recomp_entrypoint,
        .on_init_callback = on_game_init,
    },
};

// std::terminate (any uncaught C++ exception, on any thread -- recomp::start
// spawns several) leads straight into ucrtbase's fail-fast abort path, which
// tears the process down without running atexit handlers or flushing stdio
// buffers. That's why redirected runs (`... > run_output.txt 2>&1`) have
// been showing up empty even when something threw and printed nothing --
// this handler force-flushes and prints the exception's own message first
// so it actually survives redirection.
[[noreturn]] static void report_unhandled_exception_and_abort() {
    if (std::exception_ptr eptr = std::current_exception()) {
        try {
            std::rethrow_exception(eptr);
        } catch (const std::exception& e) {
            fprintf(stderr, "UNHANDLED EXCEPTION: %s\n", e.what());
        } catch (...) {
            fprintf(stderr, "UNHANDLED EXCEPTION: (unrecognized exception type)\n");
        }
    } else {
        fprintf(stderr, "std::terminate() called with no active exception.\n");
    }
    fflush(stdout);
    fflush(stderr);
    std::abort();
}

// Gamepad defaults, changed from RecompFrontend's to a layout tested to play
// well here: the right stick is the N64 stick with its vertical axis inverted,
// the left stick the C buttons (its click is C-Up), and the
// triggers swap, the left one R and the right one Z. Only fresh profiles and
// "Reset to defaults" use these; saved controls are kept. Must run before
// anything reads the defaults (profiles load with the config).
static void set_default_controller_mapping() {
    using recompinput::GameInput;
    using recompinput::InputField;
    auto set = recompinput::set_default_mapping_for_controller;
    set(GameInput::R,          { InputField::controller_analog(SDL_CONTROLLER_AXIS_TRIGGERLEFT, true) });
    set(GameInput::Z,          { InputField::controller_analog(SDL_CONTROLLER_AXIS_TRIGGERRIGHT, true) });
    set(GameInput::C_LEFT,     { InputField::controller_analog(SDL_CONTROLLER_AXIS_LEFTX, false), InputField::controller_digital(recompinput::SDL_CONTROLLER_BUTTON_NORTH) });
    set(GameInput::C_RIGHT,    { InputField::controller_analog(SDL_CONTROLLER_AXIS_LEFTX, true),  InputField::controller_digital(recompinput::SDL_CONTROLLER_BUTTON_EAST) });
    set(GameInput::C_UP,       { InputField::controller_analog(SDL_CONTROLLER_AXIS_LEFTY, false), InputField::controller_digital(SDL_CONTROLLER_BUTTON_LEFTSTICK) });
    set(GameInput::C_DOWN,     { InputField::controller_analog(SDL_CONTROLLER_AXIS_LEFTY, true),  InputField::controller_digital(SDL_CONTROLLER_BUTTON_RIGHTSHOULDER) });
    set(GameInput::X_AXIS_NEG, { InputField::controller_analog(SDL_CONTROLLER_AXIS_RIGHTX, false) });
    set(GameInput::X_AXIS_POS, { InputField::controller_analog(SDL_CONTROLLER_AXIS_RIGHTX, true) });
    set(GameInput::Y_AXIS_POS, { InputField::controller_analog(SDL_CONTROLLER_AXIS_RIGHTY, true) });
    set(GameInput::Y_AXIS_NEG, { InputField::controller_analog(SDL_CONTROLLER_AXIS_RIGHTY, false) });
}

int main(int argc, char** argv) {
    std::set_terminate(report_unhandled_exception_and_abort);

    recomp::Version project_version{};
    if (!recomp::Version::from_string(version_string, project_version)) {
        fprintf(stderr, "Invalid version string: %s\n", version_string.c_str());
        return EXIT_FAILURE;
    }

    register_bz_overlays();
    bz::apply_theme();

    NFD_Init();

    recompui::programconfig::set_program_name(program_name);
    recompui::programconfig::set_program_id(program_id);

    SDL_InitSubSystem(SDL_INIT_AUDIO);
    if (!open_audio_device(game_frequency)) {
        fprintf(stderr, "Continuing without sound.\n");
    }

    // Exo 2 (SIL OFL 1.1, assets/EXO2_LICENSE.txt), a variable font covering
    // every weight the UI uses. The family name must match the one stored
    // inside the font file: recompui's generated base stylesheet sets
    // `font-family` to it, and RmlUi draws no text for a family it never
    // loaded.
    recompui::register_primary_font("Exo2.ttf", "Exo 2");

    recomp::register_config_path(recompui::file::get_app_folder_path());

    for (const auto& game : supported_games) {
        recomp::register_game(game);
    }

    set_default_controller_mapping();

    recompinput::players::set_single_player_mode(true);

    // recompui::config::init_modal() (called from UIState::create_menus(),
    // itself called from inside RT64::Application::setup() on the gfx
    // thread) hard-requires recompui::config::finalize() to have already
    // run -- without it, "loaded_configs" stays false and/or the config
    // system is left in a state RT64/recompui doesn't expect, which was
    // crashing startup entirely. So the config tabs are
    // created and finalized here, before recomp::start().
    recompui::config::GeneralTabOptions general_tab_options{};
    bz::config::add_general_options(recompui::config::create_general_tab(general_tab_options));
    bz::config::add_graphics_options(recompui::config::create_graphics_tab());
    recompui::config::create_controls_tab();
    recompui::config::create_sound_tab();
    recompui::config::create_mods_tab();
    recompui::config::finalize();

    // Read from the just-loaded config; takes effect on the next launch if
    // changed in the menu.
    if (bz::config::get_local_multiplayer()) {
        recompinput::players::set_single_player_mode(false);
    }

    recomp::rsp::callbacks_t rsp_callbacks{
        .get_rsp_microcode = get_rsp_microcode,
    };

    ultramodern::renderer::callbacks_t renderer_callbacks{
        .create_render_context = [](uint8_t* rdram, ultramodern::renderer::WindowHandle window_handle, bool developer_mode) {
            auto presentation_mode = ultramodern::renderer::PresentationMode::PresentEarly;
            return recompui::renderer::create_render_context(rdram, window_handle, presentation_mode, developer_mode);
        },
    };

    ultramodern::gfx_callbacks_t gfx_callbacks{
        .create_gfx = create_gfx,
        .create_window = create_window,
        .update_gfx = update_gfx,
    };

    ultramodern::audio_callbacks_t audio_callbacks{
        .queue_samples = queue_samples,
        .get_frames_remaining = get_frames_remaining,
        .set_frequency = set_frequency,
    };

    ultramodern::input::callbacks_t input_callbacks{
        .poll_input = recompinput::poll_inputs,
        .get_input = recompinput::profiles::get_n64_input,
        .set_rumble = recompinput::set_rumble,
        .get_connected_device_info = get_connected_device_info,
    };

    ultramodern::events::callbacks_t events_callbacks{
        .vi_callback = recompinput::update_rumble,
        .gfx_init_callback = nullptr,
    };

    ultramodern::error_handling::callbacks_t error_handling_callbacks{
        .message_box = recompui::message_box,
    };

    ultramodern::threads::callbacks_t threads_callbacks{
        .get_game_thread_name = get_game_thread_name,
    };

    // recompui's own default launcher menu is used -- no
    // register_launcher_init_callback call here (see file-level comment).

    recomp::start({
        .argc = argc,
        .argv = argv,
        .project_version = project_version,
        .window_handle = {}, // created by gfx_callbacks.create_window
        .rsp_callbacks = rsp_callbacks,
        .renderer_callbacks = renderer_callbacks,
        .audio_callbacks = audio_callbacks,
        .input_callbacks = input_callbacks,
        .gfx_callbacks = gfx_callbacks,
        .events_callbacks = events_callbacks,
        .error_handling_callbacks = error_handling_callbacks,
        .threads_callbacks = threads_callbacks,
        .message_queue_control = {}, // the runtime's defaults
    });

    NFD_Quit();

    // The game's threads are never joined by the runtime and may still be
    // blocked on (or spinning over) runtime state when recomp::start
    // returns, so running static destructors/atexit handlers underneath
    // them can crash on quit -- exit directly instead (same approach as
    // other N64Recomp projects' main()).
    fflush(stdout);
    fflush(stderr);
    std::_Exit(EXIT_SUCCESS);
}
