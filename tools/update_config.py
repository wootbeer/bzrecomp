#!/usr/bin/env python3
"""Rewrite the generated part of battlezone.us.rev0.toml (everything after the
GENERATED marker) from the current symbol file:

  * a yield hook in every busy-wait loop (tools/scan_spin_loops.py), and
  * jr_targets for every jump table tools/find_functions.py resolved
    (BattlezoneSyms/*.jtables.json). N64Recomp handles the tables it can
    decode itself and uses these for the ones it can't (e.g. a table pointer
    stepped through in a loop instead of indexed).

Usage: update_config.py <rom.z64>   (run from the repo root, after find_functions.py)
"""
import json
import re
import subprocess
import sys

CONFIG = "battlezone.us.rev0.toml"
SYMS = "BattlezoneSyms/battlezone.us.rev0.syms.toml"
JTABLES = "BattlezoneSyms/battlezone.us.rev0.syms.jtables.json"
MARKER = "# ---- GENERATED by tools/update_config.py: edits below this line are overwritten ----\n"


def main():
    rom = sys.argv[1]
    funcs = {}
    for m in re.finditer(r'name = "(\w+)", vram = (0x[0-9a-f]+), size = (0x[0-9a-f]+)', open(SYMS).read()):
        funcs[m.group(1)] = (int(m.group(2), 16), int(m.group(3), 16))

    # libultra functions N64Recomp replaces or skips by name aren't compiled.
    special = set(re.findall(r'"(\w+)"', open("lib/N64ModernRuntime/N64Recomp/src/symbol_lists.cpp").read()))

    hooks = subprocess.run([sys.executable, "tools/scan_spin_loops.py", rom, SYMS, "--toml"],
                           check=True, capture_output=True, text=True).stdout

    out = [MARKER, "\n# Busy-waits (tools/scan_spin_loops.py).\n", hooks.lstrip("\n")]
    out.append("\n# Jump tables (tools/find_functions.py) as possible jr targets.\n")
    seen = set()
    for t in json.load(open(JTABLES)):
        f = funcs.get(t["func"])
        if f is None or t["jr"] in seen or t["func"] in special:
            continue
        start, end = f[0], f[0] + f[1]
        if not (start <= t["jr"] < end) or not all(start <= x < end for x in t["targets"]):
            continue
        seen.add(t["jr"])
        targets = ", ".join(f"{x:#010x}" for x in t["targets"])
        out.append(f'\n[[patches.jr_targets]]  # table {t["table"]:#010x}\n'
                   f'func = "{t["func"]}"\nvram = {t["jr"]:#010x}\ntargets = [{targets}]\n')

    text = open(CONFIG).read()
    if MARKER in text:
        text = text[:text.index(MARKER)]
    open(CONFIG, "w").write(text.rstrip("\n") + "\n\n" + "".join(out))
    print(f"{hooks.count('[[patches.hook]]')} busy-wait hooks, {len(seen)} jump tables")


if __name__ == "__main__":
    main()
